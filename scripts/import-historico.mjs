async function run() {
  console.log(`📦 Importando ${historico.length} registros...`);

  // Get editor IDs to link
  const { data: editores } = await supabase.from("editores").select("id, nome");
  const editorMap = Object.fromEntries((editores ?? []).map(e => [e.nome.toLowerCase(), e.id]));

  // Batch insert in chunks of 50
  const chunkSize = 50;
  let inserted = 0;

  for (let i = 0; i < historico.length; i += chunkSize) {
    const chunk = historico.slice(i, i + chunkSize).map(r => ({
      mes: r.mes,
      clinica: r.clinica,
      editor_id: editorMap[r.editor_nome?.toLowerCase()] ?? null,
      editor_nome: r.editor_nome,
      status: r.status,
      data_pedido: r.data_pedido,
      entrega: r.entrega,
      qtde: r.qtde,
      fila_edicao: r.fila_edicao,
      caminho_arquivo: r.caminho_arquivo,
      subiu_campanha: r.subiu_campanha,
      observacao: r.observacao || null,
    }));

    const { error } = await supabase.from("pedidos").insert(chunk);
    if (error) {
      console.error(`❌ Erro no chunk ${i}:`, error.message);
    } else {
      inserted += chunk.length;
      console.log(`✅ ${inserted}/${historico.length} registros inseridos`);
    }
  }

  console.log(`\n🎉 Importação concluída! ${inserted} pedidos importados.`);
}

run().catch(console.error);
